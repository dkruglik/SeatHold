import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const blocklistUrl =
  "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";
export const minimumDomains = 1000;

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const outputFile = path.join(repoRoot, "backend", "data", "disposable-email-domains.txt");

const domainPattern = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;

/** Lowercase, trim, drop comments and anything that is not a dotted domain, dedupe, sort. */
export function parseBlocklist(text) {
  const domains = new Set();
  for (const line of text.split(/\r?\n/)) {
    const entry = line.trim().toLowerCase();
    if (domainPattern.test(entry)) {
      domains.add(entry);
    }
  }
  return [...domains].sort();
}

export function assertEnoughDomains(domains) {
  if (domains.length < minimumDomains) {
    throw new Error(
      `Refusing to write a list of ${domains.length} domains: expected at least ${minimumDomains}`,
    );
  }
}

export function buildDomainFile(domains) {
  const header = [
    "# Disposable email domains, one per line, sorted.",
    "# Source: https://github.com/disposable-email-domains/disposable-email-domains (CC0 1.0).",
    `# Generated by scripts/update-disposable-domains.mjs from ${blocklistUrl}`,
    "# Review the diff in git before committing a refresh.",
  ];
  return `${[...header, ...domains].join("\n")}\n`;
}

async function main() {
  const response = await fetch(blocklistUrl, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) {
    throw new Error(`Download failed: HTTP ${response.status}`);
  }
  const domains = parseBlocklist(await response.text());
  assertEnoughDomains(domains);
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, buildDomainFile(domains));
  console.log(`Wrote ${domains.length} domains to ${path.relative(repoRoot, outputFile)}`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
